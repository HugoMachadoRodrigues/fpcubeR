d <- fpc_example_dir()

test_that("lineage: identifiers, parents and statuses", {
  l <- fpc_lineage(dir = d)
  expect_equal(names(l), c("field_id", "fid", "status", "parent_field_id", "parent_fid", "n_pixels", "obs_version"))
  expect_setequal(unique(l$status), c("unchanged", "reshaped", "new", "removed"))
  expect_true(all(is.na(l$field_id[l$status == "removed"])))
  expect_true(all(l$field_id[l$status != "removed"] == sprintf("FPC%06d", l$fid[l$status != "removed"])))
  # tier C fields have no version 1.0 parent; unchanged and reshaped fields are their own parent
  f <- fpc_fields(dir = d, geometry = FALSE)
  expect_true(all(is.na(l$parent_fid[l$field_id %in% f$field_id[f$tier == "C"]])))
  same <- l$status %in% c("unchanged", "reshaped")
  expect_equal(l$parent_fid[same], l$fid[same])
  expect_true(all(l$obs_version[l$status == "unchanged"] == "v1.0"))
  # every example field is in the lineage
  expect_setequal(fpc_lineage(fields = f, dir = d)$field_id, f$field_id)
  s <- fpc_lineage(parents = "FPC057124", dir = d)
  expect_setequal(s$status, c("reshaped", "new"))
  expect_true(all(s$parent_field_id == "FPC057124"))
  expect_equal(nrow(fpc_lineage(status = "removed", dir = d)), 1)
  expect_error(fpc_lineage(status = "gone", dir = d), "Unknown status")
})

test_that("validation tables", {
  v <- fpc_validation(dir = d)
  expect_equal(nrow(v), 6)
  expect_true(all(file.exists(file.path(d, "validation", v$file))))
  f <- fpc_fields(dir = d, geometry = FALSE)
  w <- fpc_validation("worldcover_by_field", dir = d)
  expect_equal(names(w)[1:2], c("field_id", "fid"))
  expect_setequal(w$field_id, f$field_id)
  shares <- rowSums(w[, setdiff(names(w), c("field_id", "fid"))])
  expect_true(all(abs(shares - 1) < 1e-6))
  fl <- fpc_validation("fluccs_by_field", fields = f$field_id[1:2], dir = d)
  expect_equal(nrow(fl), 2)
  # FLUCCS pixel counts add up to the field size
  px <- rowSums(fl[, setdiff(names(fl), c("field_id", "fid", "district"))])
  expect_equal(px, fpc_lineage(fields = fl$field_id, dir = d)$n_pixels)
  cy <- fpc_validation("coverage_by_year", dir = d)
  expect_true("year" %in% names(cy))
  expect_equal(min(cy$year), 2016)
  q <- fpc_validation("quality_by_stratum", dir = d)
  expect_setequal(unique(q$size), c("2-5 ha", "5-20 ha", "20-100 ha", ">=100 ha"))
  expect_type(fpc_validation("summary", dir = d), "list")
  expect_error(fpc_validation("nope", dir = d), "Unknown validation table")
  expect_error(fpc_validation("summary", fields = "FPC000001", dir = d), "per-field")
})

test_that("benchmark tables", {
  b <- fpc_benchmark(dir = d)
  expect_true(all(c("task1_samples", "task1_results", "task3_confusion_momentum", "benchmark_text") %in% b$table))
  expect_false(any(b$description == ""))
  expect_equal(b$task[b$table == "task2_events"], 2L)
  s <- fpc_benchmark("task1_samples", dir = d)
  f <- fpc_fields(dir = d, geometry = FALSE)
  expect_true(all(s$field_id %in% f$field_id))
  expect_true(all(s$horizon_days %in% c(15, 30, 45, 60)))
  expect_equal(as.numeric(s$target_start - s$issue_date), s$horizon_days - 5)
  expect_true(all(s$split %in% c("train", "val", "test", "test_spatial")))
  expect_equal(as.numeric(format(s$issue_date[s$t == 12][1], "%j")), 61)   # period 12 starts on 1 March 2016
  one <- fpc_benchmark("task1_samples", fields = f$field_id[1], dir = d)
  expect_true(nrow(one) > 0 && all(one$field_id == f$field_id[1]))
  # a sample's target period is observed in the composites
  x <- fpc_composites(f$field_id[1], vars = "ndvi", years = 2022, dir = d)
  t22 <- one[format(one$target_start, "%Y") == "2022", ]
  expect_true(all(x$n_optical_obs[match(t22$target_start, x$date)] > 0))
  cm <- fpc_benchmark("task3_confusion_momentum", dir = d)
  expect_equal(names(cm), c("observed", "better", "same", "worse"))
  expect_equal(names(fpc_benchmark("task1_lightgbm_importance", dir = d)), c("feature", "gain"))
  expect_s3_class(fpc_benchmark("task2_events", dir = d)$date, "Date")
  expect_type(fpc_benchmark("task1_run_info", dir = d), "list")
  expect_error(fpc_benchmark("nope", dir = d), "Unknown benchmark table")
  expect_error(fpc_benchmark("task1_results", fields = "FPC000001", dir = d), "task1_samples")
})

test_that("missing parts give helpful errors", {
  tmp <- withr_tempdir()
  expect_error(fpc_lineage(dir = tmp), "fpc_download\\(\"lineage\"\\)")
  expect_error(fpc_validation(dir = tmp), "fpc_download\\(\"validation\"\\)")
  expect_error(fpc_benchmark(dir = tmp), "fpc_download\\(\"benchmark\"\\)")
})
